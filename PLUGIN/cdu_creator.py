    # metodo per estrarre i numeri di da un testo, considerando anche intervalli di numeri separati da trattini
    def estrai_articoli_da_testo(self, val_raw):
        testo = str(val_raw)
        numeri = set()

        for start, end in re.findall(r'(\d+)\s*[-–]\s*(\d+)', testo):
            s = int(start)
            e = int(end)
            if e < s:
                s, e = e, s
            numeri.update(range(s, e + 1))

        testo = re.sub(r'\d+\s*[-–]\s*\d+', ' ', testo)

        for n in re.findall(r'\d+', testo):
            numeri.add(int(n))

        return sorted(numeri)
